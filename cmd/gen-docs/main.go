// Command gen-docs writes the CLI command reference (docs/COMMANDS.md) by
// walking the real cobra command tree.
//
// The reference must never be hand-maintained: a hand-written table drifts the
// moment a verb is added, and a drifted reference is worse than none because a
// reader trusts it. Generating from the tree makes drift impossible — the file
// can only say what the binary actually registers.
//
// Usage:
//
//	go run ./cmd/gen-docs [--out PATH] [--check]
//
// --check regenerates into memory and diffs against the file on disk, exiting
// non-zero when they differ. That is the form CI uses, so a forgotten
// regeneration fails the build instead of shipping a stale reference.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/sebihoermann/devdb-go/internal/cli"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// cobraCommand is the tree node type; aliased so the walk reads cleanly.
type cobraCommand = cobra.Command

// pflagFlag is a single flag in the tree.
type pflagFlag = pflag.Flag

// flagInfo is one rendered flag row.
type flagInfo struct {
	Name     string
	Usage    string
	DefValue string
}

func main() {
	out := flag.String("out", "docs/COMMANDS.md", "output path")
	check := flag.Bool("check", false, "diff against the file on disk instead of writing")
	flag.Parse()

	if err := run(*out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "gen-docs:", err)
		os.Exit(1)
	}
}

func run(outPath string, check bool) error {
	root := cli.NewRootForDocs()

	var buf bytes.Buffer
	renderReference(&buf, root)

	if !check {
		if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
			return err
		}
		return os.WriteFile(outPath, buf.Bytes(), 0o644)
	}

	current, err := os.ReadFile(outPath)
	if err != nil {
		return fmt.Errorf("read %s: %w (run: go run ./cmd/gen-docs)", outPath, err)
	}
	if !bytes.Equal(current, buf.Bytes()) {
		return fmt.Errorf("%s is stale — regenerate with: go run ./cmd/gen-docs", outPath)
	}
	return nil
}

// renderReference walks the tree depth-first. Group commands (parents whose only
// job is to hold subcommands) are rendered as sections; leaf commands get their
// own usage block with flags, positionals, and curated examples.
func renderReference(buf *bytes.Buffer, root *cobraCommand) {
	writeHeader(buf, root)

	for _, group := range visibleChildren(root) {
		writeGroup(buf, group)
	}

	writeGlobalFlags(buf, root)
	writeExitCodes(buf)
	writeFooter(buf)
}

func writeHeader(buf *bytes.Buffer, root *cobraCommand) {
	fmt.Fprintf(buf, "# devdb command reference\n\n")
	fmt.Fprintf(buf, "<!-- Generated by `go run ./cmd/gen-docs`. Do not edit by hand;")
	fmt.Fprintf(buf, " regenerate instead. -->\n\n")
	fmt.Fprintf(buf, "%s\n\n", root.Long)
	fmt.Fprintf(buf, "Every verb below is registered by the binary. Flags are listed")
	fmt.Fprintf(buf, " with their defaults; global flags are accepted by every command.\n\n")
	fmt.Fprintf(buf, "## Usage\n\n")
	fmt.Fprintf(buf, "```text\n")
	fmt.Fprintf(buf, "devdb [global flags] <noun> <verb> [subverb] [flags] [args]\n")
	fmt.Fprintf(buf, "```\n\n")
	fmt.Fprintf(buf, "Run `devdb <noun> --help` for the verbs a noun accepts, and")
	fmt.Fprintf(buf, " `devdb help <noun> <verb> --examples` for real command shapes")
	fmt.Fprintf(buf, " plus known gotchas.\n\n")
}

func writeGroup(buf *bytes.Buffer, group *cobraCommand) {
	children := visibleChildren(group)
	if len(children) == 0 {
		// A top-level command with no subcommands (`init`, `status`, `report`)
		// is a verb in its own right, so render it at the same level as a
		// noun's section — a `####` leaf under no `##` parent is a broken
		// outline.
		writeCommand(buf, group, 2)
		return
	}

	fmt.Fprintf(buf, "## %s\n\n", commandPath(group))
	if group.Short != "" {
		fmt.Fprintf(buf, "%s\n\n", group.Short)
	}

	// Children that are themselves groups get rendered as a sub-section, so
	// `plan acceptance meet` is reachable without flattening the tree.
	var leaves, groups []*cobraCommand
	for _, c := range children {
		if len(visibleChildren(c)) > 0 {
			groups = append(groups, c)
		} else {
			leaves = append(leaves, c)
		}
	}

	if len(leaves) > 0 {
		fmt.Fprintf(buf, "| Verb | Summary |\n|---|---|\n")
		for _, c := range leaves {
			fmt.Fprintf(buf, "| `%s` | %s |\n", c.Name(), summary(c))
		}
		fmt.Fprintf(buf, "\n")
	}

	for _, c := range leaves {
		writeCommand(buf, c, 4)
	}
	for _, sub := range groups {
		fmt.Fprintf(buf, "### %s\n\n", commandPath(sub))
		if sub.Short != "" {
			fmt.Fprintf(buf, "%s\n\n", sub.Short)
		}
		fmt.Fprintf(buf, "| Verb | Summary |\n|---|---|\n")
		for _, c := range visibleChildren(sub) {
			fmt.Fprintf(buf, "| `%s` | %s |\n", c.Name(), summary(c))
		}
		fmt.Fprintf(buf, "\n")
		for _, c := range visibleChildren(sub) {
			writeCommand(buf, c, 5)
		}
	}
}

// summary falls back to the command's Long when Short is empty. A handful of
// verbs register no Short, and an empty table cell reads as "undocumented"
// when the Long text is sitting right there.
func summary(cmd *cobraCommand) string {
	if s := strings.TrimSpace(cmd.Short); s != "" {
		return escapePipes(s)
	}
	if l := firstLine(cmd.Long); l != "" {
		return escapePipes(l)
	}
	return "—"
}

func firstLine(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return strings.TrimSpace(s[:i])
	}
	return strings.TrimSpace(s)
}

func writeCommand(buf *bytes.Buffer, cmd *cobraCommand, level int) {
	path := commandPath(cmd)
	fmt.Fprintf(buf, "%s `%s`\n\n", strings.Repeat("#", level), path)

	// The Use string carries cobra's positional template ("add TITLE [flags]"),
	// which is the only machine-readable statement of what a verb takes.
	if use := strings.TrimSpace(cmd.Use); use != cmd.Name() {
		fmt.Fprintf(buf, "```text\n%s\n```\n\n", use)
	}
	if cmd.Long != "" && cmd.Long != cmd.Short {
		fmt.Fprintf(buf, "%s\n\n", cmd.Long)
	} else if cmd.Short != "" {
		fmt.Fprintf(buf, "%s\n\n", cmd.Short)
	}

	writeFlags(buf, cmd)

	if ex := cli.ExampleForDocs(commandPathKey(cmd)); ex != "" {
		fmt.Fprintf(buf, "Examples:\n\n```bash\n%s\n```\n\n", ex)
	}
}

func writeFlags(buf *bytes.Buffer, cmd *cobraCommand) {
	local := localFlags(cmd)
	if len(local) == 0 {
		return
	}
	fmt.Fprintf(buf, "| Flag | Default | Description |\n|---|---|---|\n")
	for _, f := range local {
		def := f.DefValue
		if def == "" {
			def = "—"
		}
		fmt.Fprintf(buf, "| `--%s` | %s | %s |\n", f.Name, def, escapePipes(f.Usage))
	}
	fmt.Fprintf(buf, "\n")
}

func writeGlobalFlags(buf *bytes.Buffer, root *cobraCommand) {
	fmt.Fprintf(buf, "## Global flags\n\n")
	fmt.Fprintf(buf, "Accepted by every command.\n\n")
	fmt.Fprintf(buf, "| Flag | Default | Description |\n|---|---|---|\n")
	for _, f := range persistentFlags(root) {
		def := f.DefValue
		if def == "" {
			def = "—"
		}
		fmt.Fprintf(buf, "| `--%s` | %s | %s |\n", f.Name, def, escapePipes(f.Usage))
	}
	fmt.Fprintf(buf, "\n")
}

func writeExitCodes(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "## Exit codes\n\n")
	fmt.Fprintf(buf, "| Code | Meaning |\n|---|---|\n")
	fmt.Fprintf(buf, "| 0 | success |\n")
	fmt.Fprintf(buf, "| 1 | general failure |\n")
	fmt.Fprintf(buf, "| 2 | usage error (unknown command, bad flag, invalid filter value) |\n")
	fmt.Fprintf(buf, "| 3 | entity not found |\n")
	fmt.Fprintf(buf, "| 4 | schema error |\n")
	fmt.Fprintf(buf, "| 5 | invalid value (e.g. rejected `arch add` topic) |\n")
	fmt.Fprintf(buf, "\n")
	fmt.Fprintf(buf, "Write commands print a bare entity id on stdout; human-facing")
	fmt.Fprintf(buf, " detail goes to stderr, so `id=$(devdb plan create ...)` stays clean.\n\n")
}

func writeFooter(buf *bytes.Buffer) {
	fmt.Fprintf(buf, "## Related\n\n")
	fmt.Fprintf(buf, "- [README](../README.md) — install, quick start, hub setup\n")
	fmt.Fprintf(buf, "- [Go/Python parity matrix](go-native-parity-matrix.md) — old grammar mapping\n")
	fmt.Fprintf(buf, "- [Agent skill](../skills/devdb/SKILL.md) — workflow playbook\n")
	fmt.Fprintf(buf, "- `devdb help <noun> <verb> --examples` — curated examples and gotchas\n")
}

// --- helpers ---------------------------------------------------------------

func visibleChildren(cmd *cobraCommand) []*cobraCommand {
	var out []*cobraCommand
	for _, c := range cmd.Commands() {
		if !c.IsAvailableCommand() || c.IsAdditionalHelpTopicCommand() {
			continue
		}
		out = append(out, c)
	}
	// Cobra sorts by name when EnableCommandSorting is on (the default), but
	// sort explicitly so the output is stable regardless of that setting.
	sort.Slice(out, func(i, j int) bool { return out[i].Name() < out[j].Name() })
	return out
}

func localFlags(cmd *cobraCommand) []flagInfo {
	var out []flagInfo
	cmd.LocalFlags().VisitAll(func(f *pflagFlag) {
		out = append(out, flagInfo{Name: f.Name, Usage: f.Usage, DefValue: f.DefValue})
	})
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func persistentFlags(root *cobraCommand) []flagInfo {
	var out []flagInfo
	root.PersistentFlags().VisitAll(func(f *pflagFlag) {
		out = append(out, flagInfo{Name: f.Name, Usage: f.Usage, DefValue: f.DefValue})
	})
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// commandPath is the full invocation path ("plan acceptance meet"), which is
// what a reader types and what the doc-verb lint resolves.
func commandPath(cmd *cobraCommand) string {
	var parts []string
	for c := cmd; c != nil; c = c.Parent() {
		parts = append([]string{c.Name()}, parts...)
	}
	return strings.Join(parts, " ")
}

// commandPathKey strips the leading "devdb" so it matches examplesByCommand's
// keys, which are keyed as "noun verb".
func commandPathKey(cmd *cobraCommand) string {
	return strings.TrimPrefix(commandPath(cmd), "devdb ")
}

func escapePipes(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}
